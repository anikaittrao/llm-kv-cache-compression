"""Paired bootstrap CIs for the follow-up comparisons quoted in the papers (2026-11-23, results-auditor items M1-M3, m4, m6).

Run:  .venv\\Scripts\\python.exe experiments\\rerun_2026-11-22\\followup_cis.py
Reads the per-window NLL stored in the c*.json files of this folder (read-only) and writes followup_cis.json here.
Uses experiments/stats_utils.ppl_ratio (10,000 resamples, seed 0, 95% percentile CI, windows won, exact sign test).
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from stats_utils import ppl_ratio  # noqa: E402


def load(name):
    with open(os.path.join(HERE, name)) as f:
        return json.load(f)


out = {'note': 'ratio = ppl(A)/ppl(B) on the same windows; generated by followup_cis.py'}
PAIRS = {
    'c2_kv_synergy.json': [('static / top-attended 31 + own', 'static / random 31 + own'),
                           ('static / sliding 32', 'static / random 31 + own'),
                           ('static / sliding 32', 'static / block 32'),
                           ('static / block 32', 'static / B=1')],
    'c5_kv_baselines.json': [(m, 'update / buffer 32') for m in ('sink+window f=0.92', 'H2O f=0.92', 'int4 + buffer 32',
                                                                  'int8 + buffer 32', 'int2 + buffer 32')]
                            + [('int4 + buffer 32', 'offline / buffer 32'), ('int8 + buffer 32', 'dense'),
                               ('int4 + buffer 32', 'dense'), ('sink+window f=0.92', 'dense'), ('H2O f=0.92', 'dense'),
                               ('update / buffer 32', 'dense')],
    'c11_rope_smollm2.json': [('attn-late / buffer 32', 'update / buffer 32'),
                              ('attn-late / no buffer', 'static / no buffer'),
                              ('attn-late / buffer 32', 'static / buffer 32')],
}
for f, pairs in PAIRS.items():
    d = load(f)
    nll, tok = d['nll_per_window'], d['tokens_per_window']
    out[f] = {f'{a} | {b}': ppl_ratio(nll[a], nll[b], tok) for a, b in pairs}
d = load('c1_kv_buffer.json')['settings']['KV 256/512 P=768']  # fresh windows 16-31 (added 2026-11-23, gap item G3)
out['c1_kv_buffer.json'] = {f'{a} | {b}': ppl_ratio(d['nll_per_window'][a], d['nll_per_window'][b], d['tokens_per_window'])
                            for a, b in [('static / buffer B=128', 'update / buffer B=32'),
                                         ('static / buffer B=64', 'update / buffer B=32')]}
d = load('c10_kv_cheapupdate_fd.json')['settings']['KV 256/512 P=768']
out['c10_kv_cheapupdate_fd.json'] = {'fd every 32 | brand every 32': ppl_ratio(d['nll_per_window']['fd every 32'],
                                                                             d['nll_per_window']['brand every 32'],
                                                                             d['tokens_per_window'])}
with open(os.path.join(HERE, 'followup_cis.json'), 'w') as f:
    json.dump(out, f, indent=1)
for f, v in out.items():
    if isinstance(v, dict):
        for k, r in v.items():
            print(f'{f[:6]} {k:55s} {r["ratio"]:.5f} ({r["ci_lo"]:.4f}-{r["ci_hi"]:.4f}) won {r["windows_won"]}/{r["windows"]} p {r["sign_p"]:.3f}')
